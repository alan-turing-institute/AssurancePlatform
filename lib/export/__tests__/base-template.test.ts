import { describe, expect, it } from "vitest";
import type { PlainCase } from "@/lib/case/defined-terms";
import { exportCase, exportNode } from "@/src/__tests__/utils/export-case-kit";
import { DEFAULT_BRANDING } from "../schemas/branding-config";
import type { TemplatePreset } from "../schemas/template-config";
import { createTemplateFromPreset } from "../templates";
import type { ContentBlock, RenderedDocument } from "../types";

/**
 * G1 -> S1 -> [P1 -> E1, P2 -> G-deep, G-edge]: seven elements, and goals at
 * depths 0, 2 and 3.
 */
function sampleCase(): PlainCase {
	const evidence = exportNode({ id: "e1", type: "EVIDENCE", name: "E1" });
	const deepGoal = exportNode({ id: "g3", type: "GOAL", name: "G-deep" });
	const edgeGoal = exportNode({ id: "g2", type: "GOAL", name: "G-edge" });
	const claimOne = exportNode({
		id: "p1",
		type: "PROPERTY_CLAIM",
		name: "P1",
		children: [evidence],
	});
	const claimTwo = exportNode({
		id: "p2",
		type: "PROPERTY_CLAIM",
		name: "P2",
		children: [deepGoal],
	});
	const strategy = exportNode({
		id: "s1",
		type: "STRATEGY",
		name: "S1",
		children: [claimOne, claimTwo, edgeGoal],
	});
	const root = exportNode({
		id: "g1",
		type: "GOAL",
		name: "G1",
		children: [strategy],
	});
	return exportCase(root, { name: "Sample case", description: "About it" });
}

const PRESETS: TemplatePreset[] = ["full-report", "summary", "evidence-list"];

function render(
	preset: TemplatePreset,
	branding?: Parameters<typeof createTemplateFromPreset>[1]
): Promise<RenderedDocument> {
	return createTemplateFromPreset(preset, branding).render({
		caseData: sampleCase(),
	});
}

function blocksOf(document: RenderedDocument, type: string): ContentBlock[] {
	const section = document.sections.find((s) => s.type === type);
	if (!section) {
		throw new Error(`no ${type} section`);
	}
	return section.blocks;
}

describe("base template", () => {
	describe("element count", () => {
		it.each(
			PRESETS
		)("counts every element of the tree in %s", async (preset) => {
			const document = await render(preset);

			expect(document.metadata.elementCount).toBe(7);
		});

		it("counts a lone element as one", async () => {
			const lone = exportCase(exportNode({ id: "g1", type: "GOAL" }));
			const document = await createTemplateFromPreset("summary").render({
				caseData: lone,
			});

			expect(document.metadata.elementCount).toBe(1);
		});
	});

	describe("branding", () => {
		it("hands every branding value given to the document", async () => {
			const document = await render("full-report", {
				primaryColour: "#111111",
				secondaryColour: "#222222",
				logoUrl: "https://example.com/logo.png",
				logoBase64: "bG9nbw==",
				organisationName: "Example Org",
				footerText: "Custom footer",
				fontFamily: "Courier, monospace",
			});

			expect(document.branding).toStrictEqual({
				primaryColour: "#111111",
				secondaryColour: "#222222",
				logoUrl: "https://example.com/logo.png",
				logoBase64: "bG9nbw==",
				organisationName: "Example Org",
				footerText: "Custom footer",
				fontFamily: "Courier, monospace",
			});
		});

		it("fills in the default colours, footer and font when none are given", async () => {
			const document = await render("summary");

			expect(document.branding).toStrictEqual({
				primaryColour: DEFAULT_BRANDING.primaryColour,
				secondaryColour: DEFAULT_BRANDING.secondaryColour,
				logoUrl: undefined,
				logoBase64: undefined,
				organisationName: undefined,
				footerText: "Generated by TEA Platform",
				fontFamily: DEFAULT_BRANDING.fontFamily,
			});
		});
	});

	describe("element filter", () => {
		it("lists only goals within the summary's depth limit", async () => {
			const document = await render("summary");

			const headings = blocksOf(document, "goals")
				.filter((b) => b.type === "heading")
				.map((b) => b.text);

			expect(headings).toStrictEqual(["Goals", "Goal: G1", "Goal: G-edge"]);
		});
	});

	describe("content blocks", () => {
		it("builds the title page from a heading, a paragraph and a divider", async () => {
			const document = await render("full-report");

			const [heading, paragraph, divider] = blocksOf(document, "title-page");

			expect(heading).toStrictEqual({
				type: "heading",
				level: 1,
				text: "Sample case",
			});
			expect(paragraph).toStrictEqual({ type: "paragraph", text: "About it" });
			expect(divider).toStrictEqual({ type: "divider" });
		});

		it("builds the statistics as a table with its header row and counts", async () => {
			const document = await render("full-report");

			const table = blocksOf(document, "executive-summary").find(
				(b) => b.type === "table"
			);

			expect(table).toStrictEqual({
				type: "table",
				headers: ["Metric", "Count"],
				rows: [
					["Total Elements", "7"],
					["Goals", "3"],
					["Strategies", "1"],
					["Property Claims", "2"],
					["Evidence Items", "1"],
				],
			});
		});

		it("builds the diagram section's image block with its alt text and caption", async () => {
			const document = await createTemplateFromPreset("full-report").render({
				caseData: sampleCase(),
				diagramImage: {
					data: "data:image/png;base64,AAAA",
					format: "png",
				},
			});

			expect(blocksOf(document, "diagram")).toStrictEqual([
				{
					type: "image",
					src: "data:image/png;base64,AAAA",
					alt: "Diagram for Sample case",
					caption: "Assurance Case Structure",
				},
			]);
		});
	});
});

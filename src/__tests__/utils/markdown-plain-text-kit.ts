/**
 * Shared helpers for the Markdown plain-text tests: a small reader that tells
 * what a Markdown viewer would show for a line, and finders for the places
 * where a viewer would start markup (unescaped characters, link targets).
 */

import type { PlainTreeNode } from "@/lib/case/defined-terms";
import { MarkdownExporter } from "@/lib/export/exporters/markdown-exporter";
import type { ContentBlock, RenderedDocument } from "@/lib/export/types";

const ASCII_PUNCTUATION = /[!-/:-@[-`{-~]/;
const NUMERIC_REFERENCE = /^&#(?:[0-9]{1,7}|[xX][0-9a-fA-F]{1,6});/;
const NAMED_REFERENCE = /^&([A-Za-z][A-Za-z0-9]{1,31});/;
const FRONT_MATTER = /^---\n([\s\S]*?)\n---\n/;
const SPACE_OR_TAB = /[ \t]/;
const CONTROL_OR_SPACE = /[\s\p{Cc}]/u;

/** The character references a viewer decodes, as far as the tests need. */
const NAMED_CHARACTERS: Record<string, string> = {
	amp: "&",
	apos: "'",
	ast: "*",
	bsol: "\\",
	colon: ":",
	commat: "@",
	copy: "©",
	dollar: "$",
	equals: "=",
	excl: "!",
	gt: ">",
	lbrack: "[",
	lcub: "{",
	lpar: "(",
	lsqb: "[",
	lt: "<",
	nbsp: " ",
	num: "#",
	percnt: "%",
	period: ".",
	quest: "?",
	quot: '"',
	rbrack: "]",
	rcub: "}",
	rpar: ")",
	rsqb: "]",
	semi: ";",
	sol: "/",
	vert: "|",
	verbar: "|",
};


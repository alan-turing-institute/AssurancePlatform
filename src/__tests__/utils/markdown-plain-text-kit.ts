export function createDocument(
	blocks: ContentBlock[],
	overrides: {
		caseDescription?: string;
		caseName?: string;
		exportedBy?: string;
		organisationName?: string;
		sectionTitle?: string;
	} = {}
): RenderedDocument {
	return {
		metadata: {
			caseName: overrides.caseName ?? "Test Case",
			caseDescription: overrides.caseDescription ?? "A test case",
			exportedAt: "2024-01-15T10:00:00Z",
			exportedBy: overrides.exportedBy,
			version: "1.0",
			elementCount: 1,
			format: "markdown",
		},
		branding: {
			primaryColour: "#1e40af",
			secondaryColour: "#64748b",
			footerText: "Generated by TEA Platform",
			fontFamily: "Inter, sans-serif",
			organisationName: overrides.organisationName,
		},
		sections: [
			{
				type: "goals",
				title: overrides.sectionTitle ?? "Goals",
				blocks,
			},
		],
	};
}

export function createNode(overrides: Partial<PlainTreeNode>): PlainTreeNode {
	return {
		id: "node-1",
		type: "GOAL",
		name: "G1",
		description: "",
		inSandbox: false,
		children: [],
		...overrides,
	};
}

export async function exportMarkdown(
	document: RenderedDocument
): Promise<string> {
	const result = await exporter.export(document, { caseName: "Test Case" });
	if (!(result.success && "content" in result)) {
		throw new Error("the Markdown export did not return text");
	}
	return result.content;
}

/** The YAML block at the top of the file, and everything after it. */
export function splitFrontMatter(markdown: string): {
	body: string;
	frontMatter: string;
} {
	const match = FRONT_MATTER.exec(markdown);
	if (!match) {
		return { frontMatter: "", body: markdown };
	}
	return {
		frontMatter: match[1] ?? "",
		body: markdown.slice(match[0].length),
	};
}

function decodeReference(
	rest: string
): { length: number; text: string } | null {
	const numeric = NUMERIC_REFERENCE.exec(rest);
	if (numeric) {
		const digits = numeric[0].slice(2, -1);
		const isHex = digits.startsWith("x") || digits.startsWith("X");
		const code = isHex
			? Number.parseInt(digits.slice(1), 16)
			: Number.parseInt(digits, 10);
		return { length: numeric[0].length, text: String.fromCodePoint(code) };
	}
	const named = NAMED_REFERENCE.exec(rest);
	const decoded = named ? NAMED_CHARACTERS[named[1] ?? ""] : undefined;
	return named && decoded !== undefined
		? { length: named[0].length, text: decoded }
		: null;
}

/**
 * What a viewer shows for a piece of Markdown text: a backslash before a
 * punctuation mark gives the mark itself, and a character reference gives its
 * character. A reference whose ampersand is escaped stays as written.
 */
export function readAs(text: string): string {
	let shown = "";
	let index = 0;
	while (index < text.length) {
		const character = text.charAt(index);
		if (character === "\\" && ASCII_PUNCTUATION.test(text.charAt(index + 1))) {
			shown += text.charAt(index + 1);
			index += 2;
			continue;
		}
		const reference =
			character === "&" ? decodeReference(text.slice(index)) : null;
		if (reference) {
			shown += reference.text;
			index += reference.length;
			continue;
		}
		shown += character;
		index += 1;
	}
	return shown;
}

/** Positions of `character` that no backslash escapes. */
export function unescapedPositions(text: string, character: string): number[] {
	const positions: number[] = [];
	let index = 0;
	while (index < text.length) {
		const current = text.charAt(index);
		if (current === "\\" && ASCII_PUNCTUATION.test(text.charAt(index + 1))) {
			index += 2;
			continue;
		}
		if (current === character) {
			positions.push(index);
		}
		index += 1;
	}
	return positions;
}

interface ReadTarget {
	end: number;
	target: string;
}

interface Link {
	/** Index just after the `](`. */
	from: number;
	target: string;
	/** Index of the `)` that closes the link. */
	to: number;
}

/**
 * Where a viewer would take a link or image target: the text between the
 * parentheses after an unescaped `]`. A target in angle brackets runs to the
 * closing bracket; any other runs to the first space or the parenthesis that
 * closes it. A target that cannot end properly is not a link and is skipped.
 * Scanning resumes after each link, so text inside a target is never read as
 * a second link.
 */
function parseLinks(markdown: string): Link[] {
	const links: Link[] = [];
	let resumeAt = 0;
	for (const position of unescapedPositions(markdown, "]")) {
		if (position < resumeAt || markdown.charAt(position + 1) !== "(") {
			continue;
		}
		const read = readTarget(markdown, position + 2);
		if (read) {
			links.push({ from: position + 2, target: read.target, to: read.end - 1 });
			resumeAt = read.end;
		}
	}
	return links;
}

export function linkTargets(markdown: string): string[] {
	return parseLinks(markdown).map((link) => link.target);
}

/** The text with every link target cut out, leaving the link text and syntax. */
export function withoutLinkTargets(markdown: string): string {
	let rest = "";
	let cursor = 0;
	for (const link of parseLinks(markdown)) {
		rest += markdown.slice(cursor, link.from);
		cursor = link.to;
	}
	return rest + markdown.slice(cursor);
}

function readTarget(markdown: string, start: number): ReadTarget | null {
	let index = start;
	while (SPACE_OR_TAB.test(markdown.charAt(index))) {
		index += 1;
	}
	return markdown.charAt(index) === "<"
		? readAngleTarget(markdown, index + 1)
		: readBareTarget(markdown, index);
}

function readAngleTarget(markdown: string, start: number): ReadTarget | null {
	let target = "";
	let index = start;
	while (index < markdown.length) {
		const character = markdown.charAt(index);
		if (character === "\n" || character === "<") {
			return null;
		}
		if (
			character === "\\" &&
			ASCII_PUNCTUATION.test(markdown.charAt(index + 1))
		) {
			target += markdown.charAt(index + 1);
			index += 2;
			continue;
		}
		if (character === ">") {
			const end = endOfLink(markdown, index + 1);
			return end === null ? null : { target, end };
		}
		target += character;
		index += 1;
	}
	return null;
}

function readBareTarget(markdown: string, start: number): ReadTarget | null {
	let target = "";
	let depth = 0;
	let index = start;
	while (index < markdown.length) {
		const character = markdown.charAt(index);
		if (CONTROL_OR_SPACE.test(character)) {
			const end = endOfLink(markdown, index);
			return end === null ? null : { target, end };
		}
		if (
			character === "\\" &&
			ASCII_PUNCTUATION.test(markdown.charAt(index + 1))
		) {
			target += markdown.charAt(index + 1);
			index += 2;
			continue;
		}
		if (character === ")" && depth === 0) {
			return { target, end: index + 1 };
		}
		depth += character === "(" ? 1 : 0;
		depth -= character === ")" ? 1 : 0;
		target += character;
		index += 1;
	}
	return null;
}

/** After the target: optional spaces and a quoted title, then `)`. */
function endOfLink(markdown: string, start: number): number | null {
	let index = start;
	while (SPACE_OR_TAB.test(markdown.charAt(index))) {
		index += 1;
	}
	const character = markdown.charAt(index);
	if (character === ")") {
		return index + 1;
	}
	if (character === '"' || character === "'") {
		const close = markdown.indexOf(`${character})`, index + 1);
		return close === -1 ? null : close + 2;
	}
	return null;
}

